-- -----------------------------------------------------
-- 1. Tabela de Usuários
-- -----------------------------------------------------
CREATE TABLE usuarios (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(150) NOT NULL,
    email VARCHAR2(150) NOT NULL UNIQUE,
    senha VARCHAR2(255) NOT NULL,
    perfil VARCHAR2(30) NOT NULL CHECK (perfil IN ('Administrador', 'Líder de Projeto', 'Membro da Equipe'))
);

-- -----------------------------------------------------
-- 2. Tabela de Projetos
-- -----------------------------------------------------
CREATE TABLE projetos (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(150) NOT NULL,
    descricao CLOB
);

-- -----------------------------------------------------
-- 3. Tabela Associativa: Vínculo entre Usuários e Projetos
-- -----------------------------------------------------
CREATE TABLE usuario_projetos (
    id_usuario NUMBER(10) NOT NULL,
    id_projeto NUMBER(10) NOT NULL,
    CONSTRAINT pk_usuario_projetos PRIMARY KEY (id_usuario, id_projeto),
    CONSTRAINT fk_usuario_proj_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_proj_projeto FOREIGN KEY (id_projeto) REFERENCES projetos(id) ON DELETE CASCADE
);

-- -----------------------------------------------------
-- 4. Tabela de Demandas (Entidade Principal)
-- -----------------------------------------------------
CREATE TABLE demandas (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR2(200) NOT NULL,
    descricao CLOB NOT NULL,
    tipo VARCHAR2(30) NOT NULL CHECK (tipo IN ('Tarefa', 'Defeito', 'Melhoria', 'Documentação')),
    prioridade VARCHAR2(30) NOT NULL CHECK (prioridade IN ('Crítica', 'Alta', 'Média', 'Baixa')),
    status VARCHAR2(30) DEFAULT 'Aberta' NOT NULL CHECK (status IN ('Aberta', 'Em andamento', 'Em revisão', 'Concluída', 'Cancelada')),
    id_projeto NUMBER(10) NOT NULL,
    id_responsavel NUMBER(10) NULL,
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    data_ultima_atualizacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    prazo_finalizacao DATE NOT NULL,
    CONSTRAINT fk_demanda_projeto FOREIGN KEY (id_projeto) REFERENCES projetos(id),
    CONSTRAINT fk_demanda_responsavel FOREIGN KEY (id_responsavel) REFERENCES usuarios(id) ON DELETE SET NULL
);

-- -----------------------------------------------------
-- 5. Tabela de Comentários
-- -----------------------------------------------------
CREATE TABLE comentarios (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_demanda NUMBER(10) NOT NULL,
    id_usuario NUMBER(10) NOT NULL,
    texto_comentario CLOB NOT NULL,
    data_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_comentario_demanda FOREIGN KEY (id_demanda) REFERENCES demandas(id) ON DELETE CASCADE,
    CONSTRAINT fk_comentario_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id)
);

-- -----------------------------------------------------
-- 6. Tabela de Histórico de Alterações
-- -----------------------------------------------------
CREATE TABLE historico_alteracoes (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_demanda NUMBER(10) NOT NULL,
    id_usuario NUMBER(10) NOT NULL,
    descricao_alteracao CLOB NOT NULL,
    data_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_historico_demanda FOREIGN KEY (id_demanda) REFERENCES demandas(id) ON DELETE CASCADE,
    CONSTRAINT fk_historico_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id)
);

